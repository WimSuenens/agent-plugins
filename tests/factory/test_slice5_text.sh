#!/bin/bash
# #207 slice 5, the text seam: the reference holds the dial, the verdict format, the proof kinds and the UI self-review; the router only points to it and stays under its cap.
# Written before the text. Mechanical rules are pinned in test_slice5_path.sh and test_slice5_gate.sh; here only what a script cannot say.
# shellcheck disable=SC1091
. "$(dirname "$0")/lib.sh"
RR="$PLUGIN/references/run-roles.md"; RT="$PLUGIN/references/run-route.md"; QA="$PLUGIN/agents/qa-engineer.md"; ROUTER="$RUN_ROUTER"
ck reference-exists yes "$([ -f "$RR" ] && echo yes || echo no)"
ck router-under-cap yes "$([ "$(wc -c <"$ROUTER" | tr -d ' ')" -le 70000 ] && echo yes || echo no)"
ck router-points-at-roles-reference-from-sizing-verification-and-gate 3 "$(grep -c 'references/run-roles.md' "$ROUTER" | awk '{print ($1 >= 3) ? 3 : $1}')"
for h in "Role path and test depth" "The light verdict" "Proof per artefact kind" "UI self-review"; do
  ck "ref-section-$h" yes "$(grep -q "^## $h\$" "$RR" && echo yes || echo no)"
done
has ref-floor-words "$RR" "never dropped"
has ref-depth-proof-only "$RR" "proof-only"
has ref-depth-targeted "$RR" "targeted"
has ref-depth-full-only-after-escalation "$RR" "full"
has ref-scale-down-next-slice "$RR" "scaling down happens only at the next slice"
has ref-verdict-format-criteria "$RR" "- <id>: pass | check: <one check> | proof: P1"
has ref-verdict-format-proof "$RR" "- P1 [<kind>]: <link or path>"
has ref-light-scope "$RR" "Scope: light"
has ref-light-no-new-tests "$RR" "no new tests"
has ref-proof-screenshot "$RR" "screenshot"
has ref-proof-run-log "$RR" "run-log"
has ref-proof-scenario "$RR" "scenario-transcript"
has ref-proof-human-only "$RR" "Human-only"
has ref-proof-docs "$RR" "link-check-log"
has ref-ui-critique-file "$RR" "reviews/ui-<id>.md"
has ref-ui-qa-writes-it "$RR" "qa-engineer writes the critique"
has ref-ui-phone "$RR" "phone"
has ref-ui-desktop "$RR" "desktop"
has ref-ui-severities "$RR" "severity"
has ref-ui-rework-first "$RR" "rework"
has ref-ui-not-checked "$RR" "not checked"
has ref-ui-ux-review-optional "$RR" "ux-review"
has ref-ui-before-card-or-demo "$RR" "decision card"
hasnt ref-names-no-trigger "$RR" "Visual result"
has qa-agent-reads-reference "$QA" "references/run-roles.md"
has qa-agent-depth-dial "$QA" "proof-only"
has qa-agent-light "$QA" "Scope: light"
has qa-agent-ui-critique "$QA" "reviews/ui-"
hasnt route-no-standard-placeholder "$RT" "read \`standard\`"
has route-says-path-is-derived "$RT" "role path"
has router-gate-flag "$ROUTER" "--qa-file"
has router-skip-plan "$ROUTER" "--plan"
done_
